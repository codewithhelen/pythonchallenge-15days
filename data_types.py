# Day 1 - Python Data Types

name = "Helen"
age = 19
percentage = 86.5
is_student = True

numbers = [10, 20, 30]
subjects = ("Python", "Java", "SQL")
skills = {"Python", "Java", "HTML"}
student = {"name": "Helen", "age": 19}

print("Name:", name, type(name))
print("Age:", age, type(age))
print("Percentage:", percentage, type(percentage))
print("Student:", is_student, type(is_student))

print("List:", numbers, type(numbers))
print("Tuple:", subjects, type(subjects))
print("Set:", skills, type(skills))
print("Dictionary:", student, type(student))
